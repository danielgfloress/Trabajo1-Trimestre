DROP TABLE IF EXISTS log_eventos CASCADE;
DROP TABLE IF EXISTS lineas_pedido CASCADE;
DROP TABLE IF EXISTS pedidos CASCADE;
DROP TABLE IF EXISTS personalizaciones CASCADE;
DROP TABLE IF EXISTS almacen CASCADE;
DROP TABLE IF EXISTS modelos CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS permisos_rol CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

-- 1. ROLES
CREATE TABLE roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

-- 2. PERMISOS_ROL
CREATE TABLE permisos_rol (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER NOT NULL,
    operacion VARCHAR(60) NOT NULL,
    permitido BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_rol_operacion UNIQUE (id_rol, operacion),
    CONSTRAINT fk_permisos_rol FOREIGN KEY (id_rol) 
        REFERENCES roles(id_rol) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 3. USUARIOS
CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    id_rol INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol) 
        REFERENCES roles(id_rol) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- 4. CLIENTES
CREATE TABLE clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_odoo VARCHAR(50) UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    tipo_cliente VARCHAR(30) NOT NULL DEFAULT 'CLUB',
    email VARCHAR(100) UNIQUE,
    telefono VARCHAR(20),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_tipo_cliente CHECK (tipo_cliente IN ('CLUB', 'EQUIPO', 'PARTICULAR'))
);

-- 5. MODELOS
CREATE TABLE modelos (
    id_modelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_modelo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    precio_base NUMERIC(10,2) NOT NULL,
    admite_custom BOOLEAN NOT NULL DEFAULT TRUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_precio_base_positivo CHECK (precio_base > 0)
);

-- 6. ALMACEN
CREATE TABLE almacen (
    id_almacen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo INTEGER NOT NULL,
    talla INTEGER NOT NULL,
    color_base VARCHAR(50) NOT NULL,
    stock_disponible INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 5,
    CONSTRAINT uq_modelo_talla_color UNIQUE (id_modelo, talla, color_base),
    CONSTRAINT chk_talla_valida CHECK (talla BETWEEN 28 AND 55),
    CONSTRAINT chk_stock_no_negativo CHECK (stock_disponible >= 0),
    CONSTRAINT fk_almacen_modelo FOREIGN KEY (id_modelo) 
        REFERENCES modelos(id_modelo) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- 7. PERSONALIZACIONES
CREATE TABLE personalizaciones (
    id_personalizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_diseno VARCHAR(100) NOT NULL,
    color_primario VARCHAR(50) NOT NULL,
    color_secundario VARCHAR(50),
    texto_bordado VARCHAR(50),
    escudo_club VARCHAR(150),
    recargo_unitario NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_recargo_no_negativo CHECK (recargo_unitario >= 0)
);

-- 8. PEDIDOS
CREATE TABLE pedidos (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_pedido_custom VARCHAR(50) UNIQUE,
    id_cliente INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,
    fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    es_custom BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    importe_total NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_estado_pedido CHECK (estado IN ('BORRADOR', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT chk_importe_total CHECK (importe_total >= 0),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (id_cliente) 
        REFERENCES clientes(id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_pedidos_usuario FOREIGN KEY (id_usuario) 
        REFERENCES usuarios(id_usuario) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- 9. LINEAS_PEDIDO
CREATE TABLE lineas_pedido (
    id_linea INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL,
    id_almacen INTEGER NOT NULL,
    id_personalizacion INTEGER,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    subtotal_linea NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT chk_precio_unitario_positivo CHECK (precio_unitario >= 0),
    CONSTRAINT fk_lineas_pedido FOREIGN KEY (id_pedido) 
        REFERENCES pedidos(id_pedido) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_lineas_almacen FOREIGN KEY (id_almacen) 
        REFERENCES almacen(id_almacen) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_lineas_personalizacion FOREIGN KEY (id_personalizacion) 
        REFERENCES personalizaciones(id_personalizacion) ON DELETE SET NULL ON UPDATE CASCADE
);

-- 10. LOG_EVENTOS
CREATE TABLE log_eventos (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario INTEGER,
    tabla_afectada VARCHAR(50) NOT NULL,
    operacion VARCHAR(30) NOT NULL,
    id_registro_afectado INTEGER NOT NULL,
    resumen_cambios VARCHAR(255) NOT NULL,
    CONSTRAINT fk_log_usuario FOREIGN KEY (id_usuario) 
        REFERENCES usuarios(id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);