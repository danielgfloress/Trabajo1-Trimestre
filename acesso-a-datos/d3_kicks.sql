CREATE INDEX idx_pedidos_fecha ON pedidos (fecha_pedido);

CREATE VIEW vista_ventas_por_modelo AS
SELECT m.codigo_modelo,
       m.marca,
       m.nombre AS modelo,
       SUM(l.cantidad) AS total_pares_vendidos,
       SUM(l.subtotal_linea) AS ingresos_totales
FROM modelos m
JOIN almacen a ON a.id_modelo = m.id_modelo
JOIN lineas_pedido l ON l.id_almacen = a.id_almacen
JOIN pedidos p ON p.id_pedido = l.id_pedido
WHERE p.estado IN ('CONFIRMADO', 'ENTREGADO')
GROUP BY m.codigo_modelo, m.marca, m.nombre;
