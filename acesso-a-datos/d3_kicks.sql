DROP VIEW IF EXISTS vista_ventas_por_modelo;
DROP TABLE IF EXISTS log_eventos CASCADE;
DROP TABLE IF EXISTS lineas_pedido CASCADE;
DROP TABLE IF EXISTS pedidos CASCADE;
DROP TABLE IF EXISTS personalizaciones CASCADE;
DROP TABLE IF EXISTS almacen CASCADE;
DROP TABLE IF EXISTS modelos CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS permisos_rol CASCADE;
DROP TABLE IF EXISTS roles CASCADE;

CREATE TABLE roles (
	id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre_rol VARCHAR(50) NOT NULL,
	descripcion VARCHAR(200),
	CONSTRAINT roles_pkey PRIMARY KEY (id_rol),
	CONSTRAINT roles_nombre_rol_key UNIQUE (nombre_rol)
);

CREATE TABLE permisos_rol (
	id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_rol INTEGER NOT NULL,
	operacion VARCHAR(60) NOT NULL,
	permitido BOOLEAN NOT NULL DEFAULT FALSE,
	CONSTRAINT permisos_rol_pkey PRIMARY KEY (id_permiso),
	CONSTRAINT uq_rol_operacion UNIQUE (id_rol, operacion)
);

CREATE TABLE usuarios (
	id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
	username VARCHAR(50) NOT NULL,
	password_hash VARCHAR(255) NOT NULL,
	id_rol INTEGER NOT NULL,
	activo BOOLEAN NOT NULL DEFAULT TRUE,
	fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	id_cliente INTEGER,
	CONSTRAINT usuarios_pkey PRIMARY KEY (id_usuario),
	CONSTRAINT usuarios_username_key UNIQUE (username)
);

CREATE TABLE clientes (
	id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY,
	codigo_odoo VARCHAR(50),
	nombre VARCHAR(100) NOT NULL,
	tipo_cliente VARCHAR(30) NOT NULL DEFAULT 'CLUB',
	email VARCHAR(100),
	telefono VARCHAR(20),
	activo BOOLEAN NOT NULL DEFAULT TRUE,
	CONSTRAINT chk_tipo_cliente CHECK (tipo_cliente IN ('CLUB', 'EQUIPO', 'PARTICULAR')),
	CONSTRAINT clientes_pkey PRIMARY KEY (id_cliente),
	CONSTRAINT clientes_codigo_odoo_key UNIQUE (codigo_odoo),
	CONSTRAINT clientes_email_key UNIQUE (email)
);

CREATE TABLE modelos (
	id_modelo INTEGER GENERATED BY DEFAULT AS IDENTITY,
	codigo_modelo VARCHAR(40) NOT NULL,
	marca VARCHAR(50) NOT NULL,
	nombre VARCHAR(100) NOT NULL,
	categoria VARCHAR(30) NOT NULL,
	precio_base NUMERIC(10,2) NOT NULL,
	admite_custom BOOLEAN NOT NULL DEFAULT TRUE,
	activo BOOLEAN NOT NULL DEFAULT TRUE,
	altura_perfil VARCHAR(20) NOT NULL DEFAULT 'BAJO',
	CONSTRAINT chk_precio_base_positivo CHECK (precio_base > 0),
	CONSTRAINT modelos_pkey PRIMARY KEY (id_modelo),
	CONSTRAINT modelos_codigo_modelo_key UNIQUE (codigo_modelo),
	CONSTRAINT chk_altura_perfil CHECK (altura_perfil IN ('BAJO', 'MEDIO', 'ALTO'))
);

CREATE TABLE almacen (
	id_almacen INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_modelo INTEGER NOT NULL,
	talla INTEGER NOT NULL,
	color_base VARCHAR(50) NOT NULL,
	stock_disponible INTEGER NOT NULL DEFAULT 0,
	stock_minimo INTEGER NOT NULL DEFAULT 5,
	CONSTRAINT chk_talla_valida CHECK (talla BETWEEN 36 AND 46),
	CONSTRAINT chk_stock_no_negativo CHECK (stock_disponible >= 0),
	CONSTRAINT almacen_pkey PRIMARY KEY (id_almacen),
	CONSTRAINT uq_modelo_talla_color UNIQUE (id_modelo, talla, color_base)
);

CREATE TABLE personalizaciones (
	id_personalizacion INTEGER GENERATED BY DEFAULT AS IDENTITY,
	nombre_diseno VARCHAR(100) NOT NULL,
	color_primario VARCHAR(50) NOT NULL,
	color_secundario VARCHAR(50),
	texto_bordado VARCHAR(50),
	escudo_club VARCHAR(150),
	recargo_unitario NUMERIC(10,2) NOT NULL DEFAULT 0.00,
	CONSTRAINT chk_recargo_no_negativo CHECK (recargo_unitario >= 0),
	CONSTRAINT personalizaciones_pkey PRIMARY KEY (id_personalizacion)
);

CREATE TABLE pedidos (
	id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY,
	ref_odoo VARCHAR(20) NOT NULL,
	id_cliente INTEGER NOT NULL,
	id_usuario INTEGER NOT NULL,
	fecha_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	tipo VARCHAR(10) NOT NULL DEFAULT 'ESTANDAR',
	estado VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
	importe_total NUMERIC(10,2) NOT NULL DEFAULT 0.00,
	CONSTRAINT chk_estado_pedido CHECK (estado IN ('BORRADOR', 'CONFIRMADO', 'ENTREGADO', 'CANCELADO')),
	CONSTRAINT chk_importe_total CHECK (importe_total >= 0),
	CONSTRAINT pedidos_pkey PRIMARY KEY (id_pedido),
	CONSTRAINT pedidos_ref_odoo_key UNIQUE (ref_odoo),
	CONSTRAINT chk_tipo_pedido CHECK (tipo IN ('ESTANDAR', 'CUSTOM'))
);

CREATE TABLE lineas_pedido (
	id_linea INTEGER GENERATED BY DEFAULT AS IDENTITY,
	id_pedido INTEGER NOT NULL,
	id_almacen INTEGER NOT NULL,
	id_personalizacion INTEGER,
	cantidad INTEGER NOT NULL,
	precio_unitario NUMERIC(10,2) NOT NULL,
	subtotal_linea NUMERIC(10,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
	CONSTRAINT chk_cantidad_positiva CHECK (cantidad > 0),
	CONSTRAINT chk_precio_unitario_positivo CHECK (precio_unitario >= 0),
	CONSTRAINT lineas_pedido_pkey PRIMARY KEY (id_linea)
);

CREATE TABLE log_eventos (
	id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY,
	fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	id_usuario INTEGER,
	tabla_afectada VARCHAR(50) NOT NULL,
	operacion VARCHAR(30) NOT NULL,
	id_registro_afectado INTEGER NOT NULL,
	resumen_cambios VARCHAR(500) NOT NULL,
	accion VARCHAR(60),
	datos_antiguos JSONB,
	datos_nuevos JSONB,
	CONSTRAINT log_eventos_pkey PRIMARY KEY (id_evento),
	CONSTRAINT chk_operacion CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE'))
);

